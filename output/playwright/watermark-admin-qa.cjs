/* oxlint-disable no-unused-expressions -- Playwright CLI evaluates this function. */
async (page) => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const toggle = (name) => page.getByRole('switch', {name, exact:true});
  const fixture = 'D:/Design Mood/design-mood-web/public/hero/hero-site-1-crisp.jpg';
  const state = page.__wmState;
  assert(await toggle('사진 1 워터마크').isChecked(), 'individual ON');
  await toggle('업로드할 사진 워터마크').check();
  await page.getByLabel('현장 사진 업로드', {exact:true}).setInputFiles(fixture);
  await page.getByRole('tab', {name:'사진 3',exact:true}).waitFor();
  await page.getByRole('tab', {name:'사진 3',exact:true}).click();
  assert(await toggle('사진 3 워터마크').isChecked(), 'upload ON inherited');
  await toggle('사진 3 워터마크').uncheck();
  assert(await page.locator('.admin-image-preview .watermarked-image__bounds').count() === 0, 'individual OFF hides layer');
  await page.getByRole('button', {name:'사진 3 제거',exact:true}).click();
  await toggle('업로드할 사진 워터마크').uncheck();
  await page.getByLabel('현장 사진 업로드', {exact:true}).setInputFiles(fixture);
  await page.getByRole('tab', {name:'사진 3',exact:true}).waitFor();
  await page.getByRole('tab', {name:'사진 3',exact:true}).click();
  assert(!await toggle('사진 3 워터마크').isChecked(), 'upload OFF inherited');
  await page.getByRole('button', {name:'사진 3 제거',exact:true}).click();
  await page.getByRole('tab', {name:'사진 2',exact:true}).click();
  await toggle('사진 2 워터마크').check();
  await page.locator('.admin-photo-panel').screenshot({path:'output/playwright/watermark-admin-portrait.png'});
  await page.getByRole('button', {name:'사진 2 앞으로 이동',exact:true}).click();
  assert(await toggle('사진 1 워터마크').isChecked(), 'reorder retains flag');
  assert(await page.getByLabel('사진 제목', {exact:true}).inputValue() === '세로 사진', 'reorder retains identity');
  await page.getByRole('button', {name:'사진 1 뒤로 이동',exact:true}).click();
  await page.getByRole('tab', {name:'사진 1 대표 사진',exact:true}).click();
  await toggle('사진 1 워터마크').uncheck();
  await page.getByRole('button', {name:'저장',exact:true}).click();
  await page.getByText('변경사항 없음', {exact:true}).waitFor();
  assert(state.project.images[0].watermark === false, 'OFF saved');
  await page.reload();
  await page.getByRole('button', {name:/公開|공개 워터마크 검증용/}).click();
  assert(!await toggle('사진 1 워터마크').isChecked(), 'OFF restored after reload');
  await toggle('사진 1 워터마크').check();
  await page.getByRole('button', {name:'저장',exact:true}).click();
  await page.getByText('변경사항 없음', {exact:true}).waitFor();
  assert(state.project.images.every((image) => image.watermark === true), 'ON saved for both photos');
  await page.reload();
  await page.getByRole('button', {name:/공개 워터마크 검증용/}).click();
  assert(await toggle('사진 1 워터마크').isChecked(), 'ON restored after reload');
  await page.getByRole('button', {name:'메인 슬라이드쇼',exact:true}).click();
  assert(!await toggle('메인 사진 1 워터마크').isChecked(), 'legacy hero OFF');
  await toggle('메인 사진 1 워터마크').check();
  await toggle('추가할 메인 사진 워터마크').check();
  await page.getByLabel('메인 사진 추가', {exact:true}).setInputFiles(fixture);
  await toggle('메인 사진 3 워터마크').waitFor();
  assert(await toggle('메인 사진 3 워터마크').isChecked(), 'hero upload ON');
  await page.getByRole('button', {name:'메인 사진 3 제거',exact:true}).click();
  await toggle('추가할 메인 사진 워터마크').uncheck();
  await page.getByLabel('메인 사진 추가', {exact:true}).setInputFiles(fixture);
  await toggle('메인 사진 3 워터마크').waitFor();
  assert(!await toggle('메인 사진 3 워터마크').isChecked(), 'hero upload OFF');
  await page.getByRole('button', {name:'메인 사진 3 제거',exact:true}).click();
  // Replacement keeps this photo's explicit ON even when upload default is OFF.
  await page.getByLabel('메인 사진 1 교체', {exact:true}).setInputFiles(fixture);
  await page.getByRole('button', {name:'메인 슬라이드쇼 저장',exact:true}).waitFor({state:'visible'});
  await page.waitForFunction(() => !document.querySelector('fieldset').disabled);
  assert(await toggle('메인 사진 1 워터마크').isChecked(), 'hero replacement preserves ON');
  await page.getByRole('button', {name:'메인 슬라이드쇼 저장',exact:true}).click();
  await page.getByText('변경사항 없음', {exact:true}).waitFor();
  assert(state.hero.slides[0].watermark === true && state.hero.slides[1].watermark === false, 'hero per-photo ON/OFF saved');
  await page.reload();
  await page.getByRole('button', {name:'메인 슬라이드쇼',exact:true}).click();
  assert(await toggle('메인 사진 1 워터마크').isChecked(), 'hero ON reload');
  assert(!await toggle('메인 사진 2 워터마크').isChecked(), 'hero OFF reload');
  await page.locator('.admin-hero-slides > li').first().screenshot({path:'output/playwright/watermark-hero-admin.png'});
  await page.setViewportSize({width:390,height:844});
  await page.locator('.admin-hero-slides > li').first().screenshot({path:'output/playwright/watermark-admin-mobile.png'});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile no horizontal page overflow');
  state.adminPassed = true;
  return {admin:'PASS', saves:state.saves.length,uploads:state.uploads.length, errors:state.errors};
}
